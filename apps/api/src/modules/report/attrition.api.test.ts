// Attrition reports (coverage CL-147 and CL-148, under FR-056 and FR-058): the register of separations in a period, and the summary
// per position and per month — Opening, Additions, Separations, Closing, Average, Attrition rate = Separations / Average. One rule for
// all three (report/attrition.ts), so Opening + Additions − Separations = Closing and the monthly chain carries over. Synthetic data only.
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { uniq } from '../../../../../db/tests/fixtures.js';
import { SYSTEM_ACTOR_ID } from '../../audit/actors.js';
import { type Company, type Harness, startHarness, type TestActor } from '../../test/harness.js';
import { csvTable } from './csv.fixtures.js';
import { processReportQueue } from './service.js';

let h: Harness;
let A: Company;
let hr: TestActor;
let analyst: string;

const cells = (line: string) => [...line.matchAll(/"((?:[^"]|"")*)"/g)].map((m) => m[1]!.replace(/""/g, '"'));

async function report(a: TestActor, reportCode: string, filters: object) {
  const requested = await h.call(a, 'POST', '/v1/reports', { reportCode, filters });
  expect(requested.statusCode, requested.body).toBe(202);
  await processReportQueue(h.pool);
  const file = await h.call(a, 'GET', `/v1/reports/${requested.json().id}/download`);
  expect(file.statusCode, file.body).toBe(200);
  // The file starts with its context lines (title, filters, generated by); the table starts at its header row.
  const lines = csvTable(file.body).trimEnd().split('\r\n').map(cells);
  const [header, ...rows] = lines;
  return rows.map((row) => Object.fromEntries(header!.map((column, i) => [column, row[i]!])));
}

const ref = async (category: string, code: string) =>
  (await h.one<{ id: string }>(`select id from reference_value where company_id = $1 and category = $2 and code = $3`, [A.id, category, code])).id;

/** An employee who joined on `joined`, in `designation`; separated (last working date `lastDay`) when given; or a draft. */
async function employee(code: string, joined: string, designation: string, opts: { lastDay?: string; draft?: boolean } = {}) {
  const status = await ref('EMPLOYEE_STATUS', opts.draft ? 'DRAFT' : 'ACTIVE_CONFIRMED');
  const id = (
    await h.one<{ id: string }>(
      `insert into employee (company_id, employee_code, display_name, work_email, joining_date, employment_type_id, status_id, created_by)
       values ($1, $2, $3, $4, $5, $6, $7, $8) returning id`,
      [A.id, code, `Person ${code}`, `${code.toLowerCase()}@example.invalid`, joined, await ref('EMPLOYMENT_TYPE', 'PERMANENT'), status, SYSTEM_ACTOR_ID],
    )
  ).id;
  await h.db.query(
    `insert into employment_assignment (company_id, employee_id, department_id, location_id, designation_id, effective_from) values ($1, $2, $3, $4, $5, $6)`,
    [A.id, id, A.dept, A.loc, designation, joined],
  );
  if (opts.lastDay) {
    // The separation takes effect the day after the last working date (as the exit flow records it).
    await h.db.query(
      `insert into employee_status_history (company_id, employee_id, status_id, prior_status_id, effective_date, source_kind, actor_user_id)
       values ($1, $2, $3, $4, ($5::date + 1), 'SEPARATION', $6)`,
      [A.id, id, await ref('EMPLOYEE_STATUS', 'INACTIVE_SEPARATED'), status, opts.lastDay, SYSTEM_ACTOR_ID],
    );
  }
  return id;
}

const PERIOD = { from: '2026-01-01', to: '2026-03-31' };

beforeAll(async () => {
  h = await startHarness();
  A = await h.makeCompany();
  hr = await h.actor(A, 'HR_ADMINISTRATOR');
  analyst = (
    await h.one<{ id: string }>(`insert into designation (company_id, code, name, active, created_by) values ($1, $2, 'Analyst', true, $3) returning id`, [
      A.id,
      uniq('AN').toUpperCase().replace(/[^A-Z0-9_-]/g, ''),
      SYSTEM_ACTOR_ID,
    ])
  ).id;
  await employee('ATT1', '2025-01-01', A.desig); // in post throughout
  await employee('ATT2', '2025-06-01', A.desig, { lastDay: '2026-02-15' }); // leaves mid-period
  await employee('ATT3', '2026-02-01', A.desig); // joins in the period
  await employee('ATT4', '2026-01-10', analyst, { lastDay: '2026-03-20' }); // joins and leaves in the period
  await employee('ATT5', '2025-03-01', A.desig, { lastDay: '2025-12-31' }); // left the day before the period
  await employee('ATT6', '2025-02-01', analyst, { lastDay: '2026-03-31' }); // last day is the period's last day
  await employee('ATT7', '2025-05-01', A.desig, { draft: true }); // a draft was never employed
  await employee('ATT8', '2026-04-15', A.desig); // joins after the period
}, 300_000);

afterAll(async () => {
  await h?.stop();
});

describe('attrition reports (FR-056, FR-058; coverage CL-147, CL-148)', () => {
  it('FR-056 the attrition register lists the separations of the period by last working date, with type and tenure', async () => {
    const rows = await report(hr, 'ATTRITION_REGISTER', PERIOD);
    expect(rows.map((r) => [r['Employee code'], r['Last working date']])).toEqual([
      ['ATT2', '2026-02-15'],
      ['ATT4', '2026-03-20'],
      ['ATT6', '2026-03-31'],
    ]);
    const att2 = rows.find((r) => r['Employee code'] === 'ATT2')!;
    expect(att2['Joining date']).toBe('2025-06-01');
    expect(att2['Tenure (years)']).toBe('0.7');
    expect(rows.find((r) => r['Employee code'] === 'ATT4')!['Position']).toBe('Analyst');
    // Someone who left before the period, a draft and a later joiner are not separations of the period.
    expect(rows.some((r) => ['ATT5', 'ATT7', 'ATT8'].includes(r['Employee code']!))).toBe(false);
  });

  it('FR-058 the summary by position: opening + additions − separations = closing; rate = separations / average', async () => {
    const rows = await report(hr, 'ATTRITION_SUMMARY', PERIOD);
    const by = Object.fromEntries(rows.map((r) => [r['Position'], r]));
    const engineer = rows.find((r) => r['Position'] !== 'Analyst' && r['Position'] !== 'All positions')!;
    expect([engineer['Opening'], engineer['Additions'], engineer['Separations'], engineer['Closing'], engineer['Average'], engineer['Attrition rate (%)']]).toEqual(['2', '1', '1', '2', '2.0', '50.00']);
    expect([by['Analyst']!['Opening'], by['Analyst']!['Additions'], by['Analyst']!['Separations'], by['Analyst']!['Closing'], by['Analyst']!['Attrition rate (%)']]).toEqual(['1', '1', '2', '0', '400.00']);
    const all = by['All positions']!;
    expect([all['Opening'], all['Additions'], all['Separations'], all['Closing'], all['Average'], all['Attrition rate (%)']]).toEqual(['3', '2', '3', '2', '2.5', '120.00']);
    for (const r of rows) expect(Number(r['Opening']) + Number(r['Additions']) - Number(r['Separations'])).toBe(Number(r['Closing']));
    // The total row comes last.
    expect(rows.at(-1)!['Position']).toBe('All positions');
  });

  it('FR-058 the summary by month cuts the period into months whose closing is the next month\'s opening', async () => {
    const rows = await report(hr, 'ATTRITION_MONTHLY', PERIOD);
    expect(rows.map((r) => [r['Month'], r['Opening'], r['Additions'], r['Separations'], r['Closing']])).toEqual([
      ['2026-01', '3', '1', '0', '4'],
      ['2026-02', '4', '1', '1', '4'],
      ['2026-03', '4', '0', '2', '2'],
    ]);
    for (let i = 1; i < rows.length; i++) expect(rows[i]!['Opening']).toBe(rows[i - 1]!['Closing']);
  });

  it('FR-056 the reports need a period and are refused to a role without the employee export right', async () => {
    const noPeriod = await h.call(hr, 'POST', '/v1/reports', { reportCode: 'ATTRITION_REGISTER', filters: {} });
    expect(noPeriod.statusCode).toBe(422);
    const employeeRole = await h.actor(A, 'EMPLOYEE');
    const refused = await h.call(employeeRole, 'POST', '/v1/reports', { reportCode: 'ATTRITION_SUMMARY', filters: PERIOD });
    expect([403, 404]).toContain(refused.statusCode);
  });
});
